"""Builds scripts/town_layout.gd: Wicker Cove's tile grid (CCH-WICKER-COVE-ALPHA-001).

Run from the repo root:  python tools/town_layout.py
The grid is built from the rectangles below, so buildings, doors and counters always line up with their art.
Edit here and regenerate rather than editing the .gd by hand.
"""

import zlib
W, H = 40, 30            # the outdoor village
IW, IH = 14, 10          # the inn's common room
INT_ORIGIN = (0, H + 4)  # where the common room sits in the same grid (out of sight of the street)

g = [[","] * W for _ in range(H)]


def fill(x, y, w, h, c):
    for yy in range(y, y + h):
        for xx in range(x, x + w):
            g[yy][xx] = c


def put(x, y, c):
    g[y][x] = c


# Forest round the edge, thicker at the top where the road comes down the hill.
fill(0, 0, W, 2, "T")
fill(0, 2, 8, 1, "T"); fill(23, 2, W - 23, 1, "T")
for x, y in [(0, 3), (1, 3), (2, 3), (0, 4), (1, 4), (0, 5), (38, 3), (39, 3), (39, 4), (39, 5), (39, 6), (0, 9), (0, 10), (39, 10)]:
    put(x, y, "T")
fill(8, 2, 10, 1, "T"); fill(21, 2, 2, 1, "T")

# The sea and its rocky ends.
fill(0, 23, W, H - 23, "~")
fill(0, 21, 2, 9, "r"); fill(38, 21, 2, 9, "r")
fill(2, 21, 36, 2, "q")                    # the quay

# Streets: the road down from the farm, the square in front of the store, the inn lane.
fill(18, 0, 3, 21, "=")
fill(8, 9, 26, 2, "=")
fill(21, 18, 13, 2, "=")
fill(14, 18, 4, 3, "m")                    # muddy ground by the market
for x in range(18, 21):
    put(x, 0, "E")                         # the road home

# Buildings (footprints block; the art covers exactly this rectangle).
BUILDINGS = [
    # id, x, y, w, h
    ("store", 9, 3, 8, 6),
    ("house_a", 23, 3, 6, 6),
    ("house_b", 31, 4, 6, 5),
    ("inn", 24, 11, 10, 7),
    ("house_c", 8, 11, 6, 6),
    ("house_d", 1, 12, 6, 5),
    ("market", 7, 17, 7, 4),
]
for _id, x, y, w, h in BUILDINGS:
    fill(x, y, w, h, "H")
put(14, 8, "c")                            # the store's half-door counter (Thomas)
put(13, 8, "N")                            # the notice board on the store's front wall
put(29, 17, "D")                           # the inn's door
for x in range(8, 13):
    put(x, 20, "F")                        # the fish market's counter

# Water features: the pier and the moored boats.
fill(19, 23, 2, 6, "k")
fill(16, 24, 2, 4, "b")
fill(22, 25, 2, 4, "b")

# Props (block): sign, lamps, crates, barrels, nets, a bench, bollards.
put(21, 3, "S")
for x, y in [(17, 5), (21, 12), (21, 20), (23, 19), (34, 19)]:
    put(x, y, "L")
for x, y in [(8, 7), (8, 8), (14, 21), (24, 21), (34, 17), (35, 17), (6, 20)]:
    put(x, y, "x")
for x, y in [(27, 21), (28, 21), (29, 21)]:
    put(x, y, "n")
put(32, 22, "B")
for x, y in [(18, 22), (21, 22)]:
    put(x, y, "o")

# The inn's common room.
inn = [
    "WWWWWWWWWWWWWW",
    "WWWWWWWWWWWWWW",
    "WWWWWWWWWWWWWW",
    "Whh...eeee..pW",
    "W.....CCCC..pW",
    "W............W",
    "W..a.....a...W",
    "W.ttt...ttt..W",
    "W..a.....a...W",
    "WWWWWWXWWWWWWW",
]
assert all(len(r) == IW for r in inn) and len(inn) == IH
assert all(len(r) == W for r in g)

terrain = ["".join(r) for r in g]
out = []
out.append("class_name TownLayout")
out.append("extends RefCounted")
out.append("")
out.append("# Wicker Cove's map (CCH-WICKER-COVE-ALPHA-001). Generated by tools/town_layout.py; regenerate rather than editing.")
out.append("# TERRAIN codes, one character per tile (blocking ones marked *):")
out.append("#   , grass   = cobbles   m mud   q quay stone   k pier boards   ~ sea*   r rocks*   T trees*   E the road home")
out.append("#   H building*   c the store counter*   N notice board*   D the inn door   F the fish market counter*")
out.append("#   S village sign*   L lamp post*   x crates and barrels*   n net rack*   B bench*   o bollard*   b boat (on the water)*")
out.append("# INTERIOR codes (the inn's common room, at INT_ORIGIN in the same grid):")
out.append("#   W wall*   . floor   h hearth*   e behind the counter*   C counter*   t table*   a chair*   p barrels*   X the way out")
out.append("")
out.append("const W := %d" % W)
out.append("const H := %d" % H)
out.append("const IW := %d" % IW)
out.append("const IH := %d" % IH)
out.append("const INT_ORIGIN := Vector2i(%d, %d)" % INT_ORIGIN)
out.append("")
out.append("const TERRAIN := [")
for r in terrain:
    out.append('\t"%s",' % r)
out.append("]")
out.append("")
out.append("const INTERIOR := [")
for r in inn:
    out.append('\t"%s",' % r)
out.append("]")
out.append("")
out.append("# id -> footprint, in outdoor tiles. The art for each is drawn to fill its rectangle.")
out.append("const BUILDINGS := {")
for _id, x, y, w, h in BUILDINGS:
    out.append('\t"%s": Rect2i(%d, %d, %d, %d),' % (_id, x, y, w, h))
out.append("}")
out.append("")
out.append("const ARRIVE := Vector2i(19, 2)          # where you come down the road")
out.append("const INN_DOOR := Vector2i(29, 17)")
out.append("const INN_OUT := Vector2i(29, 18)        # back on the lane outside the door")
out.append("const INT_ENTRY := Vector2i(6, 8)        # inside, just in from the door (local to INT_ORIGIN)")
out.append("const INT_EXIT := Vector2i(6, 9)")
out.append("const THOMAS := Vector2(14.3, 7.9)       # stands in the doorway behind his counter (tile units, feet)")
out.append("const EDITH := Vector2(8.0, 4.0)         # behind the inn counter (local tile units, feet)")
out.append("const HEARTH := Vector2i(1, 0)           # the hearth's left tile, against the north wall (local)")
out.append("const TABLES := [Vector2i(2, 7), Vector2i(8, 7)]")
out.append("const CHAIRS := [Vector2i(3, 6), Vector2i(9, 6), Vector2i(3, 8), Vector2i(9, 8)]")
out.append("")
out.append("const VERSION := \"%08x\"" % zlib.crc32(("".join(terrain) + "".join(inn)).encode()))
open("scripts/town_layout.gd", "w", newline="\n").write("\n".join(out) + "\n")
print("\n".join(terrain))
